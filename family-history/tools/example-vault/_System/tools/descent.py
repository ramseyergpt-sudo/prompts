#!/usr/bin/env python3
"""Write the lines of descent for every double ancestor (pedigree collapse).

For each person note with two or more ahnentafel numbers, writes a block
between markers showing each route from the ancestor down to the root
person (no. 1, set in settings.py), generation by generation, and where the routes meet.
Run:  python3 "_System/tools/descent.py" "/path/to/vault"
"""
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import settings as S

START = "<!-- descent:start (generated by _System/tools/descent.py; do not edit) -->"
END = "<!-- descent:end -->"
HEAD = "## Lines of descent"


def load():
    names, multi = {}, []
    for f in sorted(glob.glob("People/*.md")):
        s = open(f, encoding="utf-8").read()
        m = re.match(r"---\n(.*?)\n---", s, re.S)
        if not m:
            continue
        a = re.search(r"ahnentafel:\n((?:[ \t]+- \d+\n?)+)", m.group(1))
        if not a:
            continue
        ns = [int(x) for x in re.findall(r"\d+", a.group(1))]
        name = os.path.basename(f)[:-3]
        for n in ns:
            names.setdefault(n, name)
        if len(ns) > 1:
            multi.append((f, name, ns))
    return names, multi


def route(n):
    out = []
    while n >= 1:
        out.append(n)
        n //= 2
    return out


def label(n, names):
    if n == 1:
        return f"{S.ROOT_LABEL} (1)"
    if n == 2:
        return f"[[{names[2]}]] (2)" if 2 in names else f"{S.ROOT_LABEL}'s father (2)"
    if n == 3:
        return f"[[{names[3]}]] (3)" if 3 in names else f"{S.ROOT_LABEL}'s mother (3)"
    if n in names:
        return f"[[{names[n]}]] ({n})"
    return f"*not in the vault* ({n})"


def block(name, ns, names):
    routes = {n: route(n) for n in sorted(ns)}
    lines = [HEAD, "", START, ""]
    lines.append(
        f"This ancestor appears **{len(ns)} times** in {S.ROOT_LABEL}'s tree. "
        f"Each route below runs from the ancestor down to {S.ROOT_LABEL}, one generation per step; "
        "the number in brackets is the ahnentafel number (father = 2n, mother = 2n + 1)."
    )
    lines.append("")
    for n, r in routes.items():
        chain = " → ".join(label(x, names) for x in r)
        lines.append(f"- **Route via no. {n}** ({len(r) - 1} generations): {chain}")
    lines.append("")
    keys = sorted(routes)
    meets = []
    for i in range(len(keys)):
        for j in range(i + 1, len(keys)):
            a, b = set(routes[keys[i]]), routes[keys[j]]
            common = next(x for x in b if x in a)
            meets.append(f"routes {keys[i]} and {keys[j]} first join at {label(common, names)}")
    lines.append("**Where the routes meet:** " + "; ".join(meets) + ".")
    lines.append("")
    lines.append(END)
    return "\n".join(lines)


def main():
    if len(sys.argv) > 1:
        os.chdir(sys.argv[1])
    names, multi = load()
    for f, name, ns in multi:
        s = open(f, encoding="utf-8").read()
        new = block(name, ns, names)
        if START in s:
            pre = s[: s.index(START)]
            pre = pre[: pre.rfind(HEAD)] if HEAD in pre else pre
            post = s[s.index(END) + len(END):]
            s2 = pre + new + post
        else:
            anchor = "## Narratives and research"
            if anchor in s:
                i = s.index(anchor)
                s2 = s[:i] + new + "\n\n" + s[i:]
            else:
                s2 = s.rstrip("\n") + "\n\n" + new + "\n"
        if s2 != s:
            open(f, "w", encoding="utf-8").write(s2)
    print(f"descent: {len(multi)} double ancestors updated")


if __name__ == "__main__":
    main()
