#!/usr/bin/env python3
"""Write a "Narratives and research" section into every person and place note.

For each note in People/ and Places/, list the Stories, History events, Research
notes and other folders listed in settings.BACKLINK_FOLDERS that link to it. The
section sits between marker comments and is fully regenerated on each run, so
edit the linking notes, not this section. Run after adding notes:

    python3 "_System/tools/backlinks.py" "/path/to/Family Tree"
"""
import os, re, sys, collections

V = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import settings as S
GROUPS = S.BACKLINK_FOLDERS
# Bookkeeping notes that mention almost everyone; they would only add noise.
SKIP = S.BOOKKEEPING_NOTES
START = "<!-- backlinks:start (generated by _System/tools/backlinks.py; do not edit) -->"
END = "<!-- backlinks:end -->"
HEAD = "## Narratives and research"

def notes_in(folder):
    d = os.path.join(V, folder)
    if not os.path.isdir(d):
        return
    for r, _, fs in os.walk(d):
        if "Private" in r:
            continue
        for f in fs:
            if f.endswith(".md"):
                yield f[:-3], os.path.join(r, f)

targets = {}
for folder in ("People", "Places"):
    for n, p in notes_in(folder):
        targets[n] = p

refs = collections.defaultdict(lambda: collections.defaultdict(set))
for g in GROUPS:
    for n, p in notes_in(g):
        if n in SKIP:
            continue
        for l in set(re.findall(r"\[\[([^\]|#]+)", open(p, encoding="utf-8").read())):
            l = l.strip()
            if l in targets and l != n:
                refs[l][g].add(n)

block_re = re.compile(r"\n*" + re.escape(HEAD) + r"\n+" + re.escape(START) + r".*?" + re.escape(END) + r"\n?", re.S)
changed = 0
for n, p in targets.items():
    s = open(p, encoding="utf-8").read()
    base = block_re.sub("\n", s).rstrip("\n") + "\n"
    if refs.get(n):
        lines = [HEAD, "", START]
        for g in GROUPS:
            if refs[n].get(g):
                lines.append("- **%s:** %s" % (g, ", ".join("[[%s]]" % x for x in sorted(refs[n][g]))))
        lines.append(END)
        new = base + "\n" + "\n".join(lines) + "\n"
    else:
        new = base
    if new != s:
        open(p, "w", encoding="utf-8").write(new)
        changed += 1
print("backlinks: %d notes updated, %d with references" % (changed, len(refs)))
